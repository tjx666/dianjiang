/**
 * Antigravity CLI (`agy`) adapter.
 *
 * One-shot:  agy --print=<finalPrompt> --output-format json
 *              --dangerously-skip-permissions [--model <m>] [--effort <e>]
 * Resume:    same, plus --conversation <conversationId>.
 * Result:    stdout is a single JSON object (verified live on agy 1.4.4):
 *   { "conversation_id", "status": "SUCCESS" | "ERROR", "response", "error"?,
 *     "duration_seconds", "num_turns", "usage": { "input_tokens",
 *     "output_tokens", "thinking_tokens", "cache_read_tokens", "total_tokens" } }
 *
 * Like grok, agy's `-p`/`--print` CONSUMES the prompt as its value; agy even
 * rejects `-p --output-format json "<prompt>"` because `-p` swallowed the next
 * flag. The `--print=<prompt>` spelling keeps a prompt that starts with `-`
 * from being read as a flag.
 *
 * agy has no session-id injection: like codex, the conversation id is
 * generated by the harness and parsed from the result (`conversation_id`).
 * It has no system-prompt flag either, so instructions are prepended.
 */

import type { DispatchSpec, HarnessAdapter, HarnessResult, KnownModel, RunUsage } from '../types.ts'
import {
  asRecord,
  finalizeUsage,
  isQuotaExhaustedMessage,
  num,
  quotaExhaustedFailure,
  withInstructions,
} from './shared.ts'

/** The `--effort` values agy validates before any model-specific check. */
export const AGY_EFFORTS = ['low', 'medium', 'high', 'xhigh', 'max'] as const

/**
 * Locally-verified agy models (2026-10-22, agy 1.4.4, Google-account auth).
 * Effort support is per model and agy rejects mismatches up front:
 * - `gemini-3.8-flash` takes `--effort low|medium|high`; the `-low/-medium/-high`
 *   ids bake the effort in and reject any `--effort` ("conflicts with --effort").
 * - `gpt-oss-120b` only takes `medium`; `gpt-oss-120b-medium` bakes it in.
 * - The Claude models reject `--effort` entirely.
 *
 * No entry is marked default: agy runs the model chosen in the user's
 * `~/.gemini/antigravity-cli/settings.json` when `--model` is omitted.
 *
 * No `listModels`: `agy models` lists only the effort-suffixed ids, so live
 * enumeration would hide the effort-addressable `gemini-3.8-flash` and
 * `gpt-oss-120b`. The models offered also depend on the account (API-key auth
 * exposes others), so unknown names pass through unvalidated.
 */
export const AGY_MODELS: readonly KnownModel[] = [
  { name: 'gemini-3.8-flash', efforts: ['low', 'medium', 'high'] },
  { name: 'gemini-3.8-flash-high', efforts: [] },
  { name: 'gemini-3.8-flash-medium', efforts: [] },
  { name: 'gemini-3.8-flash-low', efforts: [] },
  { name: 'claude-sonnet-4-6', efforts: [] },
  { name: 'claude-opus-4-6-thinking', efforts: [] },
  { name: 'gpt-oss-120b', efforts: ['medium'] },
  { name: 'gpt-oss-120b-medium', efforts: [] },
]

/**
 * agy's subscription-exhaustion wording, captured live 2026-10-22:
 * `Individual quota reached. Please upgrade your subscription to increase your
 * limits. Resets in 131h11m22s.` (stderr `AGY_ERROR` carries
 * `RESOURCE_EXHAUSTED (code 429)`). `RESOURCE_EXHAUSTED` alone is not enough:
 * Google APIs also use it for transient rate limits.
 */
const AGY_QUOTA_PATTERN = /\bindividual quota reached\b/i

/** Extract agy's usage. agy reports no cost; every field stays defensive. */
function extractUsage(obj: Record<string, unknown>): RunUsage | undefined {
  const u = asRecord(obj['usage'])
  return finalizeUsage({
    inputTokens: num(u?.['input_tokens']),
    outputTokens: num(u?.['output_tokens']),
    cacheReadTokens: num(u?.['cache_read_tokens']),
    totalTokens: num(u?.['total_tokens']),
    turns: num(obj['num_turns']),
  })
}

function parseEnvelope(stdout: string): Record<string, unknown> | undefined {
  try {
    return asRecord(JSON.parse(stdout))
  } catch {
    return undefined
  }
}

export const agyAdapter: HarnessAdapter = {
  name: 'agy',
  efforts: AGY_EFFORTS,
  knownModels: AGY_MODELS,
  modelsVerifiedAt: '2026-10-22',
  versionArgs: ['--version'],

  buildCommand(spec: DispatchSpec) {
    const cmd = ['agy', `--print=${withInstructions(spec)}`, '--output-format', 'json']
    if (spec.resumeSessionId) cmd.push('--conversation', spec.resumeSessionId)
    cmd.push('--dangerously-skip-permissions')
    if (spec.model) cmd.push('--model', spec.model)
    if (spec.effort) cmd.push('--effort', spec.effort)
    return { cmd }
  },

  classifyFailure(stdout: string, stderr: string, exitCode: number) {
    const obj = parseEnvelope(stdout)
    const isError = obj?.['status'] === 'ERROR'
    if (exitCode === 0 && !isError) return undefined
    const error = obj?.['error']
    const detail = typeof error === 'string' && error.trim() ? error.trim() : (stderr.trim() || stdout.trim()).slice(-2000)
    // A SUCCESS envelope's `response` is model prose; only the error field and
    // stderr may classify a quota failure.
    const evidence = obj && !isError ? [stderr.trim()] : [detail, stderr.trim()]
    const quotaDetail = evidence.find((part) => AGY_QUOTA_PATTERN.test(part) || isQuotaExhaustedMessage(part))
    if (quotaDetail) return quotaExhaustedFailure('agy', quotaDetail.slice(-2000))
    return undefined
  },

  parseResult(spec: DispatchSpec, stdout: string): HarnessResult {
    const obj = parseEnvelope(stdout)
    if (!obj) return { result: stdout.trim(), harnessSessionId: spec.resumeSessionId ?? '' }
    const response = obj['response']
    const error = obj['error']
    let result = typeof response === 'string' ? response.trim() : ''
    if (!result && typeof error === 'string') result = error.trim()
    if (!result) result = stdout.trim()
    const conversationId = obj['conversation_id']
    const harnessSessionId =
      typeof conversationId === 'string' && conversationId ? conversationId : (spec.resumeSessionId ?? '')
    return { result, harnessSessionId, usage: extractUsage(obj) }
  },
}
